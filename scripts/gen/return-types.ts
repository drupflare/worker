/**
 * Emits the return type table the install tier uses, from anachron's `CoreReturnTypes` class.
 *
 *   bun scripts/gen/return-types.ts          rewrite the generated module
 *   bun scripts/gen/return-types.ts --check  fail if what is on disk disagrees
 *
 * The checkout is `ANACHRON_DIR`, then `../anachron`. PHP reads its own constants, so the table is
 * never parsed from source text.
 */

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..', '..');
const TARGET = resolve(ROOT, 'src', 'ops', 'generated', 'core-return-types.ts');

/** the anachron checkout, or undefined when there is none */
export function anachronCheckout(env: NodeJS.ProcessEnv = process.env): string | undefined {
	const dir = resolve(env['ANACHRON_DIR'] || join(ROOT, '..', 'anachron'));
	return existsSync(join(dir, 'src', 'Drupal', 'CoreReturnTypes.php')) ? dir : undefined;
}

/** the generated module's text for a checkout */
export function renderTable(dir: string): string {
	const script = `<?php
require ${JSON.stringify(join(dir, 'src', 'Php', 'ReturnTypeRewriter.php'))};
require ${JSON.stringify(join(dir, 'src', 'Drupal', 'CoreReturnTypes.php'))};
echo json_encode([
	'typed' => Drupflare\\Anachron\\Drupal\\CoreReturnTypes::TYPED,
	'parents' => Drupflare\\Anachron\\Drupal\\CoreReturnTypes::PARENTS,
]);`;
	const run = spawnSync('php', [], { input: script, encoding: 'utf8' });
	if (run.status !== 0) throw new Error(`php exited ${run.status}: ${run.stderr.slice(0, 300)}`);
	const table = JSON.parse(run.stdout) as {
		typed: Record<string, Record<string, string>>;
		parents: Record<string, string>;
	};
	return `// GENERATED by scripts/gen/return-types.ts from anachron's CoreReturnTypes. Do not edit.

/** return types core classes declare, by class and method name */
export const CORE_RETURN_TYPES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(table.typed, null, '\t')};

/** core classes that extend a table class without redeclaring its methods, mapped to their parent */
export const CORE_PARENTS: Readonly<Record<string, string>> = ${JSON.stringify(table.parents, null, '\t')};
`;
}

if (import.meta.main) {
	const dir = anachronCheckout();
	if (dir === undefined) {
		console.error('no anachron checkout; set ANACHRON_DIR or put one beside the worker');
		process.exit(2);
	}
	const text = renderTable(dir);
	if (process.argv.includes('--check')) {
		const held = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
		if (held !== text) {
			console.error(
				'src/ops/generated/core-return-types.ts is stale; run scripts/gen/return-types.ts'
			);
			process.exit(1);
		}
		console.log('core-return-types.ts matches anachron');
	} else {
		writeFileSync(TARGET, text);
		console.log(`wrote ${TARGET}`);
	}
}
