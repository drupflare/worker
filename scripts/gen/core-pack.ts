/**
 * Pins the per-file Drupal and WordPress packs' sha256 and length into `src/ops/generated/core-pack.ts`.
 *
 *   bun run gen:core-pack          rewrite the generated module
 *   bun run gen:core-pack --check  fail if what is on disk disagrees
 *
 * `COLD_PACK` copies `assets/drupal-pf/core.pf.bin` (or the WordPress pack) into the object's storage
 * and refuses a copy that does not match these values. A rebuilt pack changes them, so this runs
 * after `bun run assets:pack` and `bun run assets:wordpress`.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..', '..');
const PACK = resolve(ROOT, 'assets', 'drupal-pf', 'core.pf.bin');
const WORDPRESS_PACK = resolve(ROOT, 'assets', 'wordpress', 'pf', 'core.pf.bin');
const TARGET = resolve(ROOT, 'src', 'ops', 'generated', 'core-pack.ts');

export function renderCorePack(bin: Uint8Array, wordpress: Uint8Array): string {
	const sha = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');
	return (
		'// GENERATED by scripts/gen/core-pack.ts from the Drupal and WordPress core.pf.bin. Do not edit.\n\n' +
		`export const CORE_PACK_DIGEST = '${sha(bin)}';\n` +
		`export const CORE_PACK_LENGTH = ${bin.length};\n` +
		`export const WORDPRESS_PACK_DIGEST = '${sha(wordpress)}';\n` +
		`export const WORDPRESS_PACK_LENGTH = ${wordpress.length};\n`
	);
}

if (import.meta.main) {
	const rendered = renderCorePack(
		new Uint8Array(readFileSync(PACK)),
		new Uint8Array(readFileSync(WORDPRESS_PACK))
	);
	if (process.argv.includes('--check')) {
		let current = '';
		try {
			current = readFileSync(TARGET, 'utf8');
		} catch {
			// a missing file is drift like any other
		}
		if (current === rendered) {
			console.log('gen-core-pack: src/ops/generated/core-pack.ts is current');
			process.exit(0);
		}
		console.error(
			'gen-core-pack: src/ops/generated/core-pack.ts is stale; run `bun run gen:core-pack`'
		);
		process.exit(1);
	}
	writeFileSync(TARGET, rendered);
	console.log(`gen-core-pack: wrote ${TARGET}`);
}
